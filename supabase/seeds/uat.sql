SELECT (l.id-1)*3 + d.offset_day+2, l.id,
  (now() AT TIME ZONE 'Europe/Warsaw')::date+d.offset_day,
  CASE WHEN d.offset_day=-1 THEN 'completed' ELSE 'active' END
FROM public."Locations" l CROSS JOIN (VALUES (-1),(0),(1)) AS d(offset_day);

-- Three item states today; yesterday completed, tomorrow pending.
-- Use the exact catalog base unit and quantity; never guess a missing unit.
WITH products AS (
  SELECT *, row_number() OVER (ORDER BY external_id) AS slot FROM public."Products"
  WHERE base_unit IS NOT NULL
), fixtures AS (
  SELECT p.*, pr.external_id,pr.name,pr.gramatura,pr.base_unit,pr.slot,
    (p.plan_date::timestamp + interval '8 hours') AT TIME ZONE 'Europe/Warsaw' AS work_time,
    (now() AT TIME ZONE 'Europe/Warsaw')::date AS today
  FROM public."Plans" p CROSS JOIN products pr WHERE pr.slot<=3
)

CREATE FUNCTION "public"."start_plan_item"("p_requester_id" bigint, "p_item_id" bigint) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'pg_catalog'
    AS $$BEGIN

  -- Dotyczy wszystkich ról. Brak lub inna data nie może uruchomić starego RPC.
  -- Blokada planu utrzymuje status/datę stabilne do końca operacji.
  PERFORM 1
  FROM public."Plans" AS date_guard_plan
  JOIN public."Plan_items" AS date_guard_item ON date_guard_item.plan_id = date_guard_plan.id
  WHERE date_guard_item.id = p_item_id
    AND date_guard_plan.plan_date = (now() AT TIME ZONE 'Europe/Warsaw')::date
  FOR UPDATE OF date_guard_plan;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Operacja jest dostępna wyłącznie dla planu na dziś' USING ERRCODE = '42501';
  END IF;


DECLARE
  v_user_location_id bigint;
  v_plan_location_id bigint;
  v_item_started_at timestamptz;
  v_item_gotowe boolean;
BEGIN

  -- Sprawdzamy pracownika
  SELECT e.location_id
  INTO v_user_location_id
  FROM public."Employees" e
  WHERE e.id = p_requester_id
    AND e.active = true;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Brak dostępu';
  END IF;

  -- Pracownik musi być przypisany do lokalu
  IF v_user_location_id IS NULL THEN
    RAISE EXCEPTION 'Pracownik nie jest przypisany do lokalu';
  END IF;

  -- Sprawdzamy pozycję + aktywny plan
  SELECT
    p.location_id,
    pi.started_at,
    COALESCE(pi.gotowe, false)
  INTO
    v_plan_location_id,
    v_item_started_at,
    v_item_gotowe
  FROM public."Plan_items" pi
  JOIN public."Plans" p
    ON p.id = pi.plan_id
  WHERE pi.id = p_item_id
    AND p.status = 'active';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Nie znaleziono pozycji w aktywnym planie';
  END IF;

  -- Tylko własny lokal
  IF v_user_location_id IS DISTINCT FROM v_plan_location_id THEN
    RAISE EXCEPTION 'Nie masz uprawnień do tego lokalu';
  END IF;

  -- Nie uruchamiamy ponownie zakończonego zadania
  IF v_item_gotowe THEN
    RAISE EXCEPTION 'Ta pozycja jest już zakończona';
  END IF;

  -- Nie resetujemy czasu przez ponowne kliknięcie
  IF v_item_started_at IS NOT NULL THEN
    RAISE EXCEPTION 'Ta pozycja jest już w trakcie pracy';
  END IF;

  UPDATE public."Plan_items"
  SET
    started_at = now(),
    completed_at = NULL,
    gotowe = false
  WHERE id = p_item_id;

END;
END;
$$;

CREATE FUNCTION "public"."update_plan_item"("p_requester_id" bigint, "p_item_id" bigint, "p_nazwa" "text", "p_ilosc" numeric, "p_jednostka" "text", "p_priorytet" "text", "p_product_external_id" bigint DEFAULT NULL::bigint) RETURNS "void"

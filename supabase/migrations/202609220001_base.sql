CREATE FUNCTION "public"."complete_plan_item"("p_requester_id" bigint, "p_item_id" bigint) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'pg_catalog'
    AS $$BEGIN

  -- Dotyczy wszystkich ról. Brak lub inna data nie może uruchomić starego RPC.
  -- Blokada planu utrzymuje status/datę stabilne do końca operacji.
  PERFORM 1
  FROM public."Plans" AS date_guard_plan
  JOIN public."Plan_items" AS date_guard_item ON date_guard_item.plan_id = date_guard_plan.id
  WHERE date_guard_item.id = p_item_id
    AND date_guard_plan.plan_date = (now() AT TIME ZONE 'Europe/Warsaw')::date
  FOR UPDATE OF date_guard_plan;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Operacja jest dostępna wyłącznie dla planu na dziś' USING ERRCODE = '42501';
  END IF;


DECLARE
  v_user_location_id bigint;
  v_plan_location_id bigint;
  v_item_started_at timestamptz;
  v_item_gotowe boolean;
BEGIN

  -- Sprawdzamy pracownika
  SELECT e.location_id
  INTO v_user_location_id
  FROM public."Employees" e
  WHERE e.id = p_requester_id
    AND e.active = true;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Brak dostępu';
  END IF;

  IF v_user_location_id IS NULL THEN
    RAISE EXCEPTION 'Pracownik nie jest przypisany do lokalu';
  END IF;

  -- Sprawdzamy pozycję + aktywny plan
  SELECT
    p.location_id,
    pi.started_at,
    COALESCE(pi.gotowe, false)
  INTO
    v_plan_location_id,
    v_item_started_at,
    v_item_gotowe
  FROM public."Plan_items" pi
  JOIN public."Plans" p
    ON p.id = pi.plan_id
  WHERE pi.id = p_item_id
    AND p.status = 'active';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Nie znaleziono pozycji w aktywnym planie';
  END IF;

  -- Tylko własny lokal
  IF v_user_location_id IS DISTINCT FROM v_plan_location_id THEN
    RAISE EXCEPTION 'Nie masz uprawnień do tego lokalu';
  END IF;

  -- Musi być wcześniej rozpoczęta
  IF v_item_started_at IS NULL THEN
    RAISE EXCEPTION 'Najpierw rozpocznij pracę';
  END IF;

  IF v_item_gotowe THEN
    RAISE EXCEPTION 'Ta pozycja jest już zakończona';
  END IF;

  -- WAŻNE:
  -- employee_id pochodzi z requester_id.
  -- Frontend nie może wskazać innego pracownika.
  UPDATE public."Plan_items"
  SET
    gotowe = true,
    completed_at = now(),
    employee_id = p_requester_id
  WHERE id = p_item_id;

END;
END;
$$;

CREATE FUNCTION "public"."complete_production_plan"("p_requester_id" bigint, "p_plan_id" bigint) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'pg_catalog'
    AS $$
declare
  v_role text;
  v_user_location_id bigint;
  v_plan_location_id bigint;
begin

  -- Sprawdzamy pracownika
  select role, location_id
  into v_role, v_user_location_id
  from public."Employees"
  where id = p_requester_id
    and active = true;

  if not found then
    raise exception 'Brak dostępu';
  end if;

  -- Employee nie może kończyć całego planu
  if v_role not in ('administrator', 'manager', 'su-chef') then
    raise exception 'Nie masz uprawnień do zakończenia planu';
  end if;

  -- Sprawdzamy lokal planu
  select location_id
  into v_plan_location_id
  from public."Plans"
  where id = p_plan_id
    and status = 'active';

  if not found then
    raise exception 'Nie znaleziono aktywnego planu';
  end if;

  -- Manager i su-chef tylko w swoim lokalu
  if v_role <> 'administrator'
     and v_user_location_id <> v_plan_location_id then
    raise exception 'Nie masz uprawnień do tego lokalu';
  end if;

  -- Kończymy plan
  update public."Plans"
  set status = 'completed'
  where id = p_plan_id;

end;
$$;

CREATE FUNCTION "public"."create_production_plan"("p_requester_id" bigint, "p_location_id" bigint, "p_plan_date" "date", "p_items" "jsonb") RETURNS bigint
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'pg_catalog'
    AS $$
declare
  v_role text;
  v_user_location_id bigint;
  v_plan_id bigint;
begin

  select role, location_id
  into v_role, v_user_location_id
  from public."Employees"
  where id = p_requester_id
    and active = true;

  if not found then
    raise exception 'Brak dostępu';
  end if;

  if v_role IS NULL OR v_role not in ('administrator', 'manager', 'su-chef') then
    raise exception 'Nie masz uprawnień do tworzenia planu';
  end if;

  if v_role <> 'administrator'
     and v_user_location_id IS DISTINCT FROM p_location_id then
    raise exception 'Nie masz uprawnień do tego lokalu';
  end if;

  insert into public."Plans" (
    plan_date,

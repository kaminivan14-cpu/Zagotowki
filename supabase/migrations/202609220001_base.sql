    v_plan_id,
    x.product_external_id,
    x.nazwa,
    x.ilosc,
    x.jednostka,
    x.priorytet,
    NULLIF(btrim(x.note), ''),
    x.ready_time,
    false
  from jsonb_to_recordset(p_items) as x(
    product_external_id bigint,
    nazwa text,
    ilosc numeric,
    jednostka text,
    priorytet text,
    note text,
    ready_time time without time zone
  );

